import test from 'node:test';
import assert from 'node:assert/strict';
import {advancedChecks} from '../src/rules/advancedRules.js';
const rules=Object.fromEntries([26,27,28,29].map(n=>[`PG0${n}`,'warning']));
const check=(stmts,framework='sql',r=rules)=>[...advancedChecks(stmts.map((stmt,offset)=>({stmt,offset})),framework,r).values()].flat().map(x=>x.ruleId);
const ddl={AlterTableStmt:{}};
const set=(value,is_local=false)=>({VariableSetStmt:{name:'lock_timeout',kind:'VAR_SET_VALUE',is_local,args:[{A_Const:{sval:{sval:value}}}]}});
const tx=kind=>({TransactionStmt:{kind:`TRANS_STMT_${kind}`}});
const index={IndexStmt:{concurrent:true}};
const col=(name,type,extra={})=>({ColumnDef:{colname:name,typeName:{names:[{String:{sval:'pg_catalog'}},{String:{sval:type}}],...extra},constraints:[{Constraint:{contype:'CONSTR_PRIMARY'}}]}});
test('opt in only',()=>assert.deepEqual(check([ddl],'sql',{}),[]));
test('missing timeout',()=>assert.deepEqual(check([ddl]),['PG026']));
test('positive session timeout',()=>assert.deepEqual(check([set('2s'),ddl]),[]));
test('zero timeout',()=>assert.deepEqual(check([set('0'),ddl]),['PG026']));
test('local outside transaction',()=>assert.deepEqual(check([set('2s',true),ddl]),['PG026']));
test('local expires on commit',()=>assert.deepEqual(check([tx('BEGIN'),set('2s',true),ddl,tx('COMMIT'),ddl]),['PG026']));
test('rollback restores session',()=>assert.deepEqual(check([tx('BEGIN'),set('2s'),tx('ROLLBACK'),ddl]),['PG026']));
test('reset invalidates',()=>assert.deepEqual(check([set('2s'),{VariableSetStmt:{kind:'VAR_RESET_ALL'}},ddl]),['PG026']));
test('mixed Prisma only',()=>assert.deepEqual(check([index,ddl],'prisma',{PG028:'warning'}),['PG028']));
test('standalone Prisma',()=>assert.deepEqual(check([index],'prisma',{PG028:'warning'}),[]));
test('integer versus bigint',()=>assert.deepEqual(check([{CreateStmt:{tableElts:[col('id','int4'),col('other','int8')]}}]),['PG027']));
test('type semantics',()=>assert.deepEqual(check([{CreateStmt:{tableElts:[col('a','varchar',{typmods:[{}]}),col('b','timestamp'),col('c','timestamptz'),col('d','varchar')]}}]),['PG029','PG029']));
