import { readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const pkg=JSON.parse(read('package.json')), lock=JSON.parse(read('package-lock.json'));
assert.equal(pkg.version,lock.version);
assert.equal(pkg.version,lock.packages[''].version);
const action=read('action.yml');
assert.match(action,/using: composite/);
assert.match(action,/npm ci --ignore-scripts/);
assert.match(action,/default: 'false'/);
for(const file of ['run','handoff','analyze','discovery','publish','report','github-api','inputs']) read(`github-action/${file}.mjs`);
const npm=process.env.npm_execpath;
assert(npm && /npm-cli\.js$/i.test(npm), 'Run via npm run test:action-release');
const output=execFileSync(process.execPath,[npm,'pack','--dry-run','--json','--ignore-scripts'],{cwd:root,encoding:'utf8',shell:false});
const [pack]=JSON.parse(output);
assert.equal(pack.version,pkg.version);
const paths=new Set(pack.files.map(f=>f.path));
for(const p of ['package.json','bin/cli.js','README.md','LICENSE']) assert(paths.has(p),`Missing ${p}`);
for(const p of paths) assert(!/(^|\/)(\.env(?:\.|$)|node_modules\/|\.git\/)|\.(pem|key)$/i.test(p),`Unexpected package file ${p}`);
console.log(`Release structure and npm manifest verified: ${pkg.name}@${pkg.version}, ${paths.size} files. Live GitHub checks still required.`);
